# Core plot function 
def make_barchart(labels, data_dict, title, outpath,
                  metric="RMSE [°]", im=0, is_=1, ylim=None,
                  figsize=(7, 3.8), rotate_x=0, ha="center"):
    """
    data_dict : {arch: [(rmse, rmse_std, mae, mae_std, r, r_std), ...]}
    Each tuple corresponds to one label in `labels`.
    """
    metrics   = ["RMSE (°)", "MAE (°)", "r"]
    im_idx    = [0, 2, 4]   # mean indices in tuple
    is_idx    = [1, 3, 5]   # std  indices in tuple
    ylims     = [None, None, (0.0, 1.15)]

    x     = np.arange(len(labels))
    n     = len(ARCHS)
    width = 0.22
    offs  = np.linspace(-(n - 1) / 2, (n - 1) / 2, n) * width

    fig, ax = plt.subplots(1, 1, figsize=figsize)
    #fig.suptitle(title, fontsize=10, fontweight="bold", y=1.02)

    

    for arch, offset in zip(ARCHS, offs):
        vals = [d[im] for d in data_dict[arch]]
        errs = [d[is_] for d in data_dict[arch]]
        ax.bar(x + offset, vals, width,
                   label=arch, color=COLORS[arch], alpha=0.88,
                   yerr=errs, capsize=2,
                   error_kw={"linewidth": 0.8, "ecolor": "black", "capsize": 0})

    
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=rotate_x, ha=ha,
                           rotation_mode="anchor")
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.yaxis.grid(True, linestyle="--", linewidth=0.5, alpha=0.6)
    ax.set_axisbelow(True)
    ax.set_ylabel(metric, fontweight="bold")
    for spine in ax.spines.values():
        spine.set_linewidth(1.5)
    ax.tick_params(width=1.5, labelsize=9)
    for label in ax.get_xticklabels() + ax.get_yticklabels():
        label.set_fontweight("bold")
    ax.xaxis.label.set_fontweight("bold")
    ax.yaxis.label.set_fontweight("bold")
    ax.title.set_fontweight("bold")
    if ylim:
        ax.set_ylim(ylim)

    # Legend only on first subplot
    handles = [plt.Rectangle((0, 0), 1, 1, color=COLORS[a], alpha=0.88) for a in ARCHS]
    ax.legend(handles, ARCHS, frameon=False, loc="upper left", bbox_to_anchor=(1.01, 1))

    fig.tight_layout()
    fig.savefig(outpath, format="svg", bbox_inches="tight")
    plt.close(fig)
    print(f"Saved: {outpath}")


