def avg2(a, b):
    """Average means, combine stds via RMS."""
    result = []
    for i, (x, y) in enumerate(zip(a, b)):
        if i % 2 == 0:  # mean index (0, 2, 4)
            result.append((x + y) / 2)
        else:           # std index (1, 3, 5)
            result.append(np.sqrt((x**2 + y**2) / 2))
    return tuple(result)

