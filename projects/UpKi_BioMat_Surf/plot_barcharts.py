def avg5(*rows):
    arr = np.array(rows)
    result = []
    for i in range(arr.shape[1]):
        if i % 2 == 0:  # mean
            result.append(arr[:, i].mean())
        else:           # std
            result.append(np.sqrt((arr[:, i]**2).mean()))
    return tuple(result)

